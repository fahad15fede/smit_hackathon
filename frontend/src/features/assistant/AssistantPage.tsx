import { SendHorizontal, Sparkles } from 'lucide-react';
import { type FormEvent, useEffect, useRef, useState } from 'react';

import { useAskAssistant } from '@/api/insights';
import { Button } from '@/components/ui/Button';
import { Card } from '@/components/ui/Card';
import { Avatar, PageHeader } from '@/components/ui/display';
import { Input } from '@/components/ui/form';
import { useCurrentUser } from '@/features/auth/auth-context';
import { cn } from '@/lib/cn';
import { isManager } from '@/lib/roles';

interface Message {
  id: number;
  from: 'user' | 'assistant';
  text: string;
  source?: string;
}

const MANAGER_PROMPTS = ['Who is on leave today?', 'Who checked in late today?', 'How many leave requests are pending?'];
const EMPLOYEE_PROMPTS = ['What is my leave balance?', 'Did I check in today?', 'How many requests do I have pending?'];

export function AssistantPage() {
  const user = useCurrentUser();
  const ask = useAskAssistant();
  const [question, setQuestion] = useState('');
  const [messages, setMessages] = useState<Message[]>([]);
  const endRef = useRef<HTMLDivElement>(null);
  const prompts = isManager(user.role) ? MANAGER_PROMPTS : EMPLOYEE_PROMPTS;

  useEffect(() => endRef.current?.scrollIntoView({ behavior: 'smooth' }), [messages, ask.isPending]);

  const send = (text: string) => {
    const trimmed = text.trim();
    if (trimmed.length < 2 || ask.isPending) return;
    setMessages((current) => [...current, { id: Date.now(), from: 'user', text: trimmed }]);
    setQuestion('');
    ask.mutate(trimmed, {
      onSuccess: ({ answer, source }) =>
        setMessages((current) => [...current, { id: Date.now(), from: 'assistant', text: answer, source }]),
      onError: (error) =>
        setMessages((current) => [...current, { id: Date.now(), from: 'assistant', text: error.message }]),
    });
  };

  const onSubmit = (event: FormEvent) => {
    event.preventDefault();
    send(question);
  };

  return (
    <>
      <PageHeader title="Assistant" description="Ask about attendance and leave. Answers only use records you are allowed to see." />
      <Card className="flex h-[calc(100vh-14rem)] min-h-[420px] flex-col">
        <div className="flex-1 space-y-5 overflow-y-auto p-5">
          {messages.length === 0 && (
            <div className="flex h-full flex-col items-center justify-center text-center">
              <span className="grid size-14 place-items-center rounded-2xl bg-brand-50 text-brand-600">
                <Sparkles className="size-7" />
              </span>
              <h2 className="mt-4 text-lg font-semibold text-slate-900">How can I help?</h2>
              <p className="mt-1 text-sm text-slate-500">Try one of these questions:</p>
              <div className="mt-5 flex flex-wrap justify-center gap-2">
                {prompts.map((prompt) => (
                  <button
                    key={prompt}
                    type="button"
                    onClick={() => send(prompt)}
                    className="rounded-full bg-white px-4 py-2 text-sm text-slate-700 shadow-sm ring-1 ring-slate-200 hover:bg-slate-50"
                  >
                    {prompt}
                  </button>
                ))}
              </div>
            </div>
          )}

          {messages.map((message) => (
            <div key={message.id} className={cn('flex gap-3', message.from === 'user' && 'flex-row-reverse')}>
              {message.from === 'user' ? (
                <Avatar name={user.employee.full_name} size="sm" />
              ) : (
                <span className="grid size-8 shrink-0 place-items-center rounded-full bg-brand-600 text-white">
                  <Sparkles className="size-4" />
                </span>
              )}
              <div
                className={cn(
                  'max-w-[75%] rounded-2xl px-4 py-2.5 text-sm whitespace-pre-line',
                  message.from === 'user' ? 'rounded-tr-sm bg-brand-600 text-white' : 'rounded-tl-sm bg-slate-100 text-slate-800',
                )}
              >
                {message.text}
                {message.source === 'gemini' && <p className="mt-1 text-[11px] text-slate-400">Generated by Gemini</p>}
              </div>
            </div>
          ))}

          {ask.isPending && (
            <div className="flex gap-3">
              <span className="grid size-8 shrink-0 place-items-center rounded-full bg-brand-600 text-white">
                <Sparkles className="size-4" />
              </span>
              <div className="flex items-center gap-1 rounded-2xl rounded-tl-sm bg-slate-100 px-4 py-3">
                {[0, 150, 300].map((delay) => (
                  <span key={delay} className="size-1.5 animate-bounce rounded-full bg-slate-400" style={{ animationDelay: `${delay}ms` }} />
                ))}
              </div>
            </div>
          )}
          <div ref={endRef} />
        </div>

        <form onSubmit={onSubmit} className="flex gap-2 border-t border-slate-100 p-4">
          <Input
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            placeholder="Ask a question…"
            maxLength={500}
            aria-label="Question"
          />
          <Button type="submit" icon={SendHorizontal} disabled={question.trim().length < 2} loading={ask.isPending}>
            Send
          </Button>
        </form>
      </Card>
    </>
  );
}
