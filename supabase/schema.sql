-- HCM Lite database schema.
-- Run once in Supabase: Dashboard -> SQL Editor -> New query -> paste this file -> Run.
-- Safe to re-run: every statement is idempotent.

create table if not exists companies (
  id            bigint generated by default as identity primary key,
  name          varchar(120) not null,
  timezone      varchar(64)  not null default 'Asia/Karachi',
  office_start  time         not null default '09:00',
  grace_minutes integer      not null default 15 check (grace_minutes between 0 and 240),
  weekend_days  varchar(80)  not null default 'saturday,sunday',
  created_at    timestamptz  not null default now()
);

create table if not exists holidays (
  id   bigint generated by default as identity primary key,
  name varchar(100) not null,
  day  date         not null unique
);

create table if not exists departments (
  id   bigint generated by default as identity primary key,
  name varchar(100) not null
);
create unique index if not exists departments_name_key on departments (lower(name));

create table if not exists leave_types (
  id           bigint generated by default as identity primary key,
  name         varchar(60) not null,
  annual_quota integer     not null check (annual_quota between 0 and 365),
  is_paid      boolean     not null default true
);
create unique index if not exists leave_types_name_key on leave_types (lower(name));

create table if not exists employees (
  id             bigint generated by default as identity primary key,
  full_name      varchar(120)   not null,
  email          varchar(255)   not null unique,
  phone          varchar(30),
  address        varchar(255),
  department_id  bigint         references departments (id) on delete set null,
  designation    varchar(100)   not null,
  join_date      date           not null,
  monthly_salary numeric(12, 2) not null default 0 check (monthly_salary >= 0),
  is_active      boolean        not null default true,
  created_at     timestamptz    not null default now()
);

create table if not exists users (
  id            bigint generated by default as identity primary key,
  email         varchar(255) not null unique,
  password_hash varchar(255) not null,
  role          varchar(20)  not null check (role in ('admin', 'hr', 'employee')),
  is_active     boolean      not null default true,
  employee_id   bigint       not null unique references employees (id) on delete cascade,
  created_at    timestamptz  not null default now()
);

create table if not exists attendance (
  id          bigint generated by default as identity primary key,
  employee_id bigint      not null references employees (id) on delete cascade,
  day         date        not null,
  check_in    timestamptz not null,
  check_out   timestamptz,
  status      varchar(20) not null check (status in ('present', 'late')),
  unique (employee_id, day)
);
create index if not exists attendance_day_idx on attendance (day);

create table if not exists leave_requests (
  id             bigint generated by default as identity primary key,
  employee_id    bigint      not null references employees (id) on delete cascade,
  leave_type_id  bigint      not null references leave_types (id),
  start_date     date        not null,
  end_date       date        not null,
  working_days   integer     not null,
  reason         text        not null,
  status         varchar(20) not null default 'pending'
                 check (status in ('pending', 'approved', 'rejected', 'cancelled')),
  reviewed_by_id bigint      references users (id) on delete set null,
  reviewed_at    timestamptz,
  review_comment text,
  created_at     timestamptz not null default now(),
  check (end_date >= start_date)
);
create index if not exists leave_requests_employee_idx on leave_requests (employee_id);
create index if not exists leave_requests_status_idx on leave_requests (status);

create table if not exists payroll_runs (
  id            bigint generated by default as identity primary key,
  month         varchar(7)  not null unique,
  status        varchar(20) not null default 'draft' check (status in ('draft', 'finalized')),
  created_by_id bigint      references users (id) on delete set null,
  finalized_at  timestamptz,
  created_at    timestamptz not null default now()
);

create table if not exists payslips (
  id             bigint generated by default as identity primary key,
  payroll_run_id bigint         not null references payroll_runs (id) on delete cascade,
  employee_id    bigint         not null references employees (id) on delete cascade,
  working_days   integer        not null,
  unpaid_days    integer        not null default 0,
  gross          numeric(12, 2) not null,
  deduction      numeric(12, 2) not null default 0,
  net            numeric(12, 2) not null,
  unique (payroll_run_id, employee_id)
);
create index if not exists payslips_employee_idx on payslips (employee_id);

create table if not exists audit_logs (
  id         bigint generated by default as identity primary key,
  actor_id   bigint       references users (id) on delete set null,
  action     varchar(120) not null,
  detail     text         not null,
  created_at timestamptz  not null default now()
);
create index if not exists audit_logs_created_idx on audit_logs (created_at desc);

create table if not exists ai_logs (
  id           bigint generated by default as identity primary key,
  user_id      bigint       references users (id) on delete set null,
  feature      varchar(30)  not null check (feature in ('chat', 'summary', 'leave_draft')),
  prompt       text         not null,
  tools_called text         not null default '',
  status       varchar(20)  not null check (status in ('ok', 'fallback', 'error', 'rate_limited')),
  latency_ms   integer      not null default 0,
  created_at   timestamptz  not null default now()
);
create index if not exists ai_logs_user_created_idx on ai_logs (user_id, created_at desc);
-- Token usage per AI call (summed over tool rounds and retries).
alter table ai_logs add column if not exists prompt_tokens     integer not null default 0;
alter table ai_logs add column if not exists completion_tokens integer not null default 0;

-- Security --------------------------------------------------------------------------
-- The FastAPI backend authenticates users itself and talks to Supabase with the secret
-- (service_role) key, which bypasses Row Level Security. Enabling RLS without any policies
-- and revoking table access from the public roles means the publishable/anon key, which is
-- shipped to browsers, cannot read or write HR data.
do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'companies', 'holidays', 'departments', 'leave_types', 'employees', 'users',
    'attendance', 'leave_requests', 'payroll_runs', 'payslips', 'audit_logs', 'ai_logs'
  ] loop
    execute format('alter table public.%I enable row level security', tbl);
    execute format('revoke all on table public.%I from anon, authenticated', tbl);
    execute format('grant select, insert, update, delete on table public.%I to service_role', tbl);
  end loop;
end
$$;
grant usage, select on all sequences in schema public to service_role;

-- Make the new tables visible to the Data API immediately.
notify pgrst, 'reload schema';
